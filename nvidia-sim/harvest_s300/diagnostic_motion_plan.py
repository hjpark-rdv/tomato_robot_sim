"""Import one independently audited prefix into the existing native runner.

The initial plan is still generated by the ordinary planner. Only its joint
preparation and exactly reversed return may differ. No new execution engine,
contact permission, or native detachment evidence is introduced here.
"""
import hashlib
import json
from pathlib import Path

import numpy as np


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _same_action(a, b):
    return all(a.get(key) == b.get(key) for key in
        ('name', 'duration_s', 'waypoint_q', 'end_gap_m', 'belt_local_y_m_s',
         'rail_waypoint_positions_m'))


def load_connected_plan(assembly, path, phases, baseline, *, native_tool_cache=None):
    """Fail closed on changed source, target, suffix, certificates, or clock."""
    assembly, path = Path(assembly).resolve(), Path(path).resolve()
    folder = path.parent
    manifest = json.loads((assembly / 'motion_manifest.json').read_text())
    fresh = manifest.get('fresh_campaign', {})
    if (fresh.get('schema') != 's300-independent-fresh-near-campaign-v1' or
            fresh.get('inherited_native_breaks') != [] or
            fresh.get('accepted_previous_route_history') is not False):
        raise ValueError('Diagnostic import requires an independent fresh source, without inherited harvest credit')
    report = json.loads((folder / 'report.json').read_text())
    if (report.get('schema') != 's300-existing-ompl-prefix-connection-v1' or
            report.get('native_eligible') is not True or
            report.get('physics_executed') is not False or
            report.get('training_eligible') is not False):
        raise ValueError('A complete, independently audited diagnostic prefix is required')
    native_cache_proof=report.get('native_tool_cache')
    if native_cache_proof is not None:
        if (native_tool_cache is None or
                Path(native_cache_proof['path']).resolve()!=Path(native_tool_cache).resolve() or
                native_cache_proof['sha256']!=digest(native_tool_cache)):
            raise ValueError('Runtime native tool pieces differ from the independently audited cache')
    elif native_tool_cache is not None:
        raise ValueError('Runtime native tool cache was not part of the independent certificate')
    if (Path(report['source_assembly']).resolve() != assembly or
            report['source_scene_sha256'] != digest(assembly / 'scene.usda') or
            report['source_scene_sha256'] != manifest['scene_sha256'] or
            report['source_usdc_sha256'] !=
            manifest['compact_assets']['materialized_dependency']['sha256']):
        raise ValueError('Diagnostic prefix source model identity mismatch')
    source_path = Path(report['source_plan']).resolve()
    artifacts = ((path, 'plan_sha256'),
                 (source_path, 'source_plan_sha256'),
                 (folder / 'self_120hz.json', 'self_120hz_sha256'),
                 (folder / 'preparation_environment_120hz.json',
                  'preparation_environment_120hz_sha256'),
                 (folder / 'full_environment_120hz.json', 'full_environment_120hz_sha256'))
    for artifact, key in artifacts:
        if report.get(key) != digest(artifact):
            raise ValueError('Diagnostic prefix artifact hash mismatch: ' + key)
    original = json.loads(source_path.read_text())
    plan = json.loads(path.read_text())
    self_check = json.loads((folder / 'self_120hz.json').read_text())
    environment = json.loads((folder / 'preparation_environment_120hz.json').read_text())
    full_environment = json.loads((folder / 'full_environment_120hz.json').read_text())
    if (not all(check.get('passed') is True and check.get('complete') is True
                for check in (self_check, environment, full_environment)) or
            environment.get('eligible_for_native_execution') is not True or
            environment.get('requested_hz') != 120 or
            full_environment.get('requested_hz') != 120):
        raise ValueError('Incomplete or failed full120Hz diagnostic prefix audit')
    base_rows = baseline['phases']
    old_rows = original['phases']
    # Planner metadata may include extra selection evidence. The actual joint,
    # jaw, belt, rail, and timing commands must be exactly the generated ones.
    if len(base_rows) != len(old_rows) or not all(
            _same_action(dict(row, rail_waypoint_positions_m=row.get('rail_waypoint_positions_m', [0., 0.])),
                         dict(old, rail_waypoint_positions_m=old.get('rail_waypoint_positions_m', [0., 0.])))
            for row, old in zip(base_rows, old_rows)):
        raise ValueError('Audited source commands differ from the newly generated target plan')
    for key in ('goal_q', 'prep_q', 'goal_pose', 'prep_pose', 'approach_direction_world',
                'pitch_deg', 'grasp_depth_m', 'grasp_height_offset_m', 'grasp_lateral_offset_m'):
        if original.get(key) != baseline.get(key) or plan.get(key) != original.get(key):
            raise ValueError('Diagnostic prefix changed the actual target or entry: ' + key)
    indices = {name: [i for i, row in enumerate(old_rows) if row['name'] == name]
               for name in ('prepare_joint_branch', 'return_joint_branch')}
    if any(len(value) != 1 for value in indices.values()):
        raise ValueError('Exactly one original joint connector and reverse return required')
    begin, back = (indices[name][0] for name in indices)
    new_rows = plan['phases']
    if full_environment.get('selected_phases') != [row['name'] for row in new_rows]:
        raise ValueError('Full environment certificate did not cover every actual phase')
    forward = [r for r in new_rows if r['name'].startswith('prepare_ompl_')]
    reverse = [r for r in new_rows if r['name'].startswith('return_ompl_')]
    if not forward or len(forward) != len(reverse):
        raise ValueError('Checked forward and reverse connected edges required')
    expected = old_rows[:begin] + forward + old_rows[begin+1:back] + reverse + old_rows[back+1:]
    if len(expected) != len(new_rows) or not all(_same_action(a, b) for a, b in zip(expected, new_rows)):
        raise ValueError('Diagnostic plan changed commands outside the two permitted connectors')
    original_q = old_rows[begin]['waypoint_q']
    if (forward[0]['waypoint_q'][0] != original_q[0] or
            forward[-1]['waypoint_q'][-1] != original_q[-1]):
        raise ValueError('Prefix did not retain exact source and staging joints')
    for i, edge in enumerate(forward):
        q = np.asarray(edge['waypoint_q'], dtype=float)
        if q.shape != (2, 7) or not np.isfinite(q).all():
            raise ValueError('Every connected edge must be finite seven-DOF endpoints')
        if i and forward[i-1]['waypoint_q'][-1] != edge['waypoint_q'][0]:
            raise ValueError('Disconnected diagnostic joint path')
        returned = reverse[-1-i]
        if returned['waypoint_q'] != edge['waypoint_q'][::-1] or returned['duration_s'] != edge['duration_s']:
            raise ValueError('Return must be the exact checked reverse route')
        for row, old_index in ((edge, begin), (returned, back)):
            if (row['end_gap_m'] != old_rows[old_index]['end_gap_m'] or
                    row['belt_local_y_m_s'] != [0., 0.] or
                    row.get('rail_waypoint_positions_m', [0., 0.]) != [0., 0.] or
                    not np.isfinite(row['duration_s']) or row['duration_s'] <= 0):
                raise ValueError('Diagnostic prefix changed jaw, belts, rail, or finite timing')
    delta = sum(row['duration_s'] for row in forward) - old_rows[begin]['duration_s']
    old_cycle, new_cycle = original.get('belt_cycle'), plan.get('belt_cycle')
    if old_cycle is not None:
        expected_cycle = dict(old_cycle, start_after_settle_s=old_cycle['start_after_settle_s'] + delta)
        if new_cycle != expected_cycle:
            raise ValueError('Continuous belt clock must follow the retimed preparation')
    # Preserve the freshly generated selection/axis metadata and import only
    # the certified command rows plus their disclosed timing change.
    result = dict(baseline, phases=new_rows, belt_cycle=new_cycle,
                  ompl_prefix_connection=plan['ompl_prefix_connection'],
                  imported_diagnostic_plan=dict(path=str(path), sha256=digest(path),
                      certificate=str(folder / 'report.json'), only_initial_cycle=True,
                      physics_executed=False, training_eligible=False))
    if native_cache_proof is not None:
        result['imported_diagnostic_plan']['native_tool_cache']=native_cache_proof
    executable = [(r['name'], r['duration_s'], np.asarray(r['waypoint_q'], dtype=float),
                   r['end_gap_m'], *r['belt_local_y_m_s']) for r in new_rows]
    return executable, result
