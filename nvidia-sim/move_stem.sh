#!/usr/bin/env bash
# ==============================================================================
# move_stem.sh - 시뮬레이션 실행 중 실시간으로 토마토 줄기/열매 위치 변경 도구
# ==============================================================================
set -eo pipefail

if [ "$#" -lt 3 ]; then
  echo "======================================================================"
  echo " [Farmily Tomato] 실시간 토마토 줄기/열매 위치 변경 도구"
  echo "======================================================================"
  echo " 시뮬레이션(run_sim.sh)을 재시작하지 않고 실행 중에 좌표를 즉각 변경합니다."
  echo ""
  echo " 사용법: $0 X Y Z [YAW_DEG]"
  echo ""
  echo " 예시:"
  echo "   $0 -0.75 1.20 0.32          # 왼쪽 배드 로봇 정면 기본 위치"
  echo "   $0 -0.75 1.50 0.45          # Y=1.5m, 높이 Z=0.45m로 즉시 이동"
  echo "   $0 -0.75 1.80 0.50 45       # Z회전(Yaw) 45도 적용하여 이동"
  echo "======================================================================"
  exit 1
fi

X="$1"
Y="$2"
Z="$3"
YAW="${4:-0.0}"

CMD_FILE="/tmp/farmily_stem_cmd.txt"
echo "${X} ${Y} ${Z} ${YAW}" >> "${CMD_FILE}"

echo "[OK] 실시간 좌표 전송 완료!"
echo "     위치: X=${X} m, Y=${Y} m, Z=${Z} m (Yaw=${YAW}°)"

if pgrep -f "run_farm_simulation.py" > /dev/null; then
  echo "     [상태] 실행 중인 Isaac Sim 프로세스에 즉시 전달되어 이동합니다."
else
  echo "     [상태] 시뮬레이션 시작 시 해당 좌표로 스폰/이동됩니다."
fi
